  async function goToNextStep() {
    if (step === 1) {
      saveStep1AndProceed(2);
      return;
    }

    if (step === 2) {
      if (!validateCurriculumBeforeProceed()) return;

      // Silent safety-net: ensure order is persisted even if reorder auto-save was skipped
      await Promise.allSettled(
        chapters.map((ch, idx) => {
          if (!ch.serverId) return Promise.resolve();
          return apiServiceHandler('PUT', `chapter/update/${ch.serverId}`, {
            courseId,
            title: ch.title.trim(),
            desc: ch.desc?.trim() || '',
            order: chapterOrderIn(chapters, idx),
            status: ch.status || 'active',
            isPublished: true,
            totalTopics: (ch.lessons?.length || 0) + (ch.quizzes?.length || 0) +
                         (ch.zoomLinks?.length || 0) + (ch.assignments?.length || 0),
          });
        })
      );

      setStep(3);
    }
  }

  async function saveChapter(idx) {
    const ch = chapters[idx];
    if (!ch.title.trim()) { toast.warning('Chapter title is required.'); return; }
    if (!courseId) { toast.warning('Please save course basic info (Step 1) first.'); return; }
    setSavingChapterIdx(idx);
    try {
      const payload = {
        courseId,
        title: ch.title.trim(),
        desc: ch.desc.trim(),
        order: chapterOrderIn(chapters, idx),
        ...(ch.isBonus ? { isBonus: true } : {}),
        status: ch.status || 'active',
        isPublished: true,
        totalTopics: (ch.lessons?.length || 0) + (ch.quizzes?.length || 0) +
                     (ch.zoomLinks?.length || 0) + (ch.assignments?.length || 0),
      };
      let serverId = ch.serverId;
      if (serverId) {
        await apiServiceHandler('PUT', `chapter/update/${serverId}`, payload);
      } else {
        const res = await apiServiceHandler('POST', 'chapter/create', payload);
        serverId = res?.data?._id;
      }
      // Quizzes are named after their chapter: rename the ones that don't match the new title.
      const newQuizTitle = quizTitleFor(payload.title);
      const renamed = (ch.quizzes || [])
        .filter(q => q.serverId && isAutoQuizTitle(q.title) && q.title !== newQuizTitle);
      const renameResults = await Promise.allSettled(
        renamed.map(q => apiServiceHandler('PUT', `topic/update/${q.serverId}`, { title: newQuizTitle })),
      );
      const renamedIds = new Set(renamed.filter((_, i) => renameResults[i].status === 'fulfilled').map(q => q.serverId));

      setChapters(prev => {
        const c = [...prev];
        const quizzes = (c[idx].quizzes || []).map(q => (renamedIds.has(q.serverId) ? { ...q, title: newQuizTitle } : q));
        c[idx] = { ...c[idx], serverId, saved: true, quizzes };
        return c;
      });
      if (renamedIds.size < renamed.length) toast.warning('Chapter saved, but some quiz titles could not be updated. Please try again.');
      else toast.success(ch.serverId ? 'Chapter updated.' : 'Chapter saved.');
    } catch (err) {
      toast.warning(err?.message || 'Failed to save chapter.');
    } finally {
      setSavingChapterIdx(null);
    }
  }

